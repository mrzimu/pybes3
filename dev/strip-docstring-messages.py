"""
Drop autodoc docstring messages from the extracted gettext templates.

Usage:
    python dev/strip-docstring-messages.py build/gettext

Docstrings are English-only source text (as required by AGENTS.md), so they are
not part of the translatable documentation: keeping them out of the catalogs
keeps the `.po` files small and stops them from churning whenever a docstring is
edited. Only the Markdown pages are translated.

The templates are filtered textually: every message that carries an autodoc
reference (`...:docstring of <object>:<line>`) is removed, message by message.

Drop this step if docstrings are ever meant to be translated as well.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

DOCSTRING_MARKER = "docstring of"
# Section headings generated by napoleon from Google-style docstrings.
NAPOLEON_HEADINGS = frozenset(
    {
        "Attributes",
        "Example",
        "Examples",
        "Methods",
        "Parameters",
        "Raises",
        "Return type",
        "Returns",
        "Warns",
        "Yields",
    }
)
# A reference to a line of a Markdown page, i.e. a message authored in the docs.
PAGE_LINE = re.compile(r"\.md:[1-9]\d*")
MSGID = re.compile(r'^msgid "((?:[^"\\]|\\.)*)"$', re.MULTILINE)


def is_generated(block: str) -> bool:
    """
    Whether a template entry comes from autodoc rather than a Markdown page.
    """
    if DOCSTRING_MARKER in block:
        return True
    if PAGE_LINE.search(block):
        return False
    match = MSGID.search(block)
    return match is not None and match.group(1) in NAPOLEON_HEADINGS


def strip_template(path: Path) -> int:
    """
    Remove docstring messages from one template, return how many were dropped.
    """
    blocks = path.read_text(encoding="utf-8").split("\n\n")
    kept = [block for block in blocks if not is_generated(block)]
    dropped = len(blocks) - len(kept)
    if dropped:
        path.write_text("\n\n".join(kept), encoding="utf-8")
    return dropped


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print("usage: python dev/strip-docstring-messages.py <pot-dir>")
        return 2

    templates = sorted(Path(argv[0]).rglob("*.pot"))
    if not templates:
        print(f"no .pot templates found under {argv[0]}")
        return 1

    dropped = sum(strip_template(template) for template in templates)
    print(f"dropped {dropped} docstring messages from {len(templates)} templates")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
